import { az } from "./dict";

export type Lang = "az" | "en";

const monthsFull: [string, string][] = [
  ["January", "Yanvar"], ["February", "Fevral"], ["March", "Mart"], ["April", "Aprel"], ["May", "May"], ["June", "İyun"],
  ["July", "İyul"], ["August", "Avqust"], ["September", "Sentyabr"], ["October", "Oktyabr"], ["November", "Noyabr"], ["December", "Dekabr"],
];
const weekdays: [string, string][] = [
  ["Monday", "Bazar ertəsi"], ["Tuesday", "Çərşənbə axşamı"], ["Wednesday", "Çərşənbə"], ["Thursday", "Cümə axşamı"],
  ["Friday", "Cümə"], ["Saturday", "Şənbə"], ["Sunday", "Bazar"],
];
const monthsShort: [string, string][] = [
  ["Jan", "Yan"], ["Feb", "Fev"], ["Mar", "Mar"], ["Apr", "Apr"], ["Jun", "İyn"], ["Jul", "İyl"],
  ["Aug", "Avq"], ["Sep", "Sen"], ["Oct", "Okt"], ["Nov", "Noy"], ["Dec", "Dek"],
];

const rules: [RegExp, (m: RegExpMatchArray) => string][] = [
  [/^(\d+) days?$/, (m) => `${m[1]} gün`],
  [/^in (\d+) days?$/, (m) => `${m[1]} gündən sonra`],
  [/^(\d+) days ago$/, (m) => `${m[1]} gün əvvəl`],
  [/^(\d+) min ago$/, (m) => `${m[1]} dəq əvvəl`],
  [/^(\d+) h ago$/, (m) => `${m[1]} saat əvvəl`],
  [/^(\d+) \/ (\d+) documents$/, (m) => `${m[1]} / ${m[2]} sənəd`],
  [/^Used (\d+)×$/, (m) => `${m[1]} dəfə istifadə olunub`],
  [/^updated (.+)$/, (m) => `yenilənib ${lookup(m[1])}`],
  [/^(.+) ends in (\d+) days$/, (m) => `${lookup(m[1] + " ends")} ${m[2]} gündən sonra`],
  [/^(.+) (\d+) days$/, (m) => `${lookup(m[1])} ${m[2]} gün`],
  [/^(\d+) steps? left$/, (m) => `${m[1]} mərhələ qalıb`],
  [/^(.+) left$/, (m) => `${lookup(m[1])} qalıb`],
  [/^Step: (.+)$/, (m) => `Mərhələ: ${lookup(m[1])}`],
  [/^Sent (.+)$/, (m) => `Göndərilib ${lookup(m[1])}`],
  [/^Started (.+)$/, (m) => `Başlayıb ${lookup(m[1])}`],
  [/^Signed (.+)$/, (m) => `İmzalanıb ${lookup(m[1])}`],
  [/^Responsible: (.+)$/, (m) => `Məsul: ${lookup(m[1])}`],
  [/^Until (.+)$/, (m) => `${lookup(m[1])}-dək`],
  [/^Completed (.+)$/, (m) => `Tamamlanıb ${lookup(m[1])}`],
  [/^starts (.+)$/, (m) => `başlayır ${lookup(m[1])}`],
  [/^(.+) days left$/, (m) => `${m[1]} gün qalıb`],
  [/^(.+) by you$/, (m) => `Sizin tərəfinizdən: ${lookup(m[1])}`],
  [/^Promoted to (.+)$/, (m) => `${lookup(m[1])} vəzifəsinə yüksəlib`],
  [/^approved by (.+)$/, (m) => `${m[1]} tərəfindən təsdiqlənib`],
  [/^Generated by HR on (.+)$/, (m) => `HR tərəfindən ${lookup(m[1])} tarixində hazırlanıb`],
];

const missing = new Set<string>();

export function lookup(s: string): string {
  const hit = az[s];
  if (hit !== undefined) return hit;
  if (s.includes(" · ")) return s.split(" · ").map(lookup).join(" · ");
  for (const [re, fn] of rules) {
    const m = s.match(re);
    if (m) return fn(m);
  }
  let out = s;
  for (const [en, a] of monthsFull) out = out.replace(new RegExp(`\\b${en}\\b`, "g"), a);
  for (const [en, a] of weekdays) out = out.replace(new RegExp(`\\b${en}\\b`, "g"), a);
  for (const [en, a] of monthsShort) out = out.replace(new RegExp(`\\b${en}\\b`, "g"), a);
  if (out === s && /[A-Za-z]{3,}/.test(s) && process.env.NODE_ENV !== "production") {
    missing.add(s);
    if (typeof window !== "undefined") (window as unknown as { __missing: string[] }).__missing = [...missing];
  }
  return out;
}

export function translate(s: string, lang: Lang, vars?: Record<string, string | number>): string {
  let out = lang === "az" ? lookup(s) : s;
  if (vars) out = out.replace(/\{(\w+)\}/g, (_, k) => String(vars[k] ?? ""));
  return out;
}
